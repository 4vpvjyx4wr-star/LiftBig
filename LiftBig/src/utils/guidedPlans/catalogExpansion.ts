function catalogFolder(slug: string, name: string, purpose: string): TemplateFolder {
  return { id: catalogFolderId(slug), name, purpose }
}

function day(
  id: string,
  name: string,
  folderId: string,
  exercises: TemplateExercise[],
  notes?: string,
): WorkoutTemplate {
  return dayTemplate(id, name, folderId, exercises, notes)
}

function circuitDay(
  id: string,
  name: string,
  folderId: string,
  exercises: TemplateExercise[],
  notes?: string,
): WorkoutTemplate {
  return { id, name, folderId, isCircuit: true, exercises, notes }
}

