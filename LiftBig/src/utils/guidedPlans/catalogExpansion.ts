function makeRepeatPlans(
  slug: string,
  folderId: string,
  exerciseFn: (planId: string, v: 'a' | 'b' | 'c') => TemplateExercise[],
  labels = ['A', 'B', 'C'],
): WorkoutTemplate[] {
  return (['a', 'b', 'c'] as const).map((v, i) => {
    const id = `plan-catalog-${slug}-${v}`
    return day(id, `${labels[i] ?? v.toUpperCase()}`, folderId, exerciseFn(id, v))
  })
}

